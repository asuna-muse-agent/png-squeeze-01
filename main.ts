const I = process.env.MAKEFUN_INPUT_DIR ?? '/input';
const O = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';
const ids = readdirSync(I).sort();
const T0 = Date.now();
for (const id of ids) {
  const tId = Date.now();
  const { width, height, rgba } = decodePng(readFileSync(join(I, id, 'image.png')));
  const tScr0 = Date.now();
  const scr = screen(rgba, width, height);
  const form = scr.form;
  const data = scr.data;
  const tScr1 = Date.now();
  const z9 = deflateSync(data, { level: 9, memLevel: 8, strategy: constants.Z_DEFAULT_STRATEGY });
  const tLd0 = Date.now();
  const ld = ldZlib(data, 12);
  const tLd1 = Date.now();
  const best = ld.length < z9.length ? Buffer.from(ld) : z9;
  console.error(JSON.stringify({ id, screenMs: tScr1 - tScr0, ld12Ms: tLd1 - tLd0, ld12Bytes: ld.length, z9Bytes: z9.length }));
  mkdirSync(join(O, id), { recursive: true });
  writeFileSync(join(O, id, 'image.png'), pngOfForm(width, height, form, new Uint8Array(best.buffer, best.byteOffset, best.length)));
  console.error(JSON.stringify({ id, fileBytes: best.length, ms: Date.now() - tId }));
}
